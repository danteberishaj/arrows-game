#!/usr/bin/env python3
"""WINTER-01: turn the Codex-painted layers into app assets (the 'Painted' menu look).

  /usr/bin/python3 scripts/art/winter/codex-post.py
Reads artifacts/WINTER-01/concepts/codex/{garland,snowscape}-{day,night}.png (Codex built-in imagegen, prompts beside
them). Crops each pair to the union of their alpha bounds (day/night stay pixel-aligned), scales to 1440 wide, adds a
warm halo under the night lights (the painted night barely glows), writes assets/images/winter/painted-*.webp and
src/ui/winter/paintedAspects.ts. Exits non-zero if an input is missing.
"""
import pathlib
import sys

from PIL import Image

SRC = pathlib.Path('artifacts/WINTER-01/concepts/codex')
OUT = pathlib.Path('assets/images/winter')
PAIRS = {'garland': 'garland', 'hills': 'snowscape'}
halo = None


def load_halo():
    # menu-post.py runs main() on import, so copy its halo() source instead of importing it.
    src = pathlib.Path('scripts/art/winter/menu-post.py').read_text()
    start = src.index('def halo(')
    end = src.index('\ndef ', start + 1)
    ns = {}
    exec('from PIL import Image, ImageChops, ImageFilter\n' + src[start:end], ns)
    return ns['halo']


def main():
    global halo
    halo = load_halo()
    missing = [f'{f}-{t}.png' for f in PAIRS.values() for t in ('day', 'night') if not (SRC / f'{f}-{t}.png').exists()]
    if missing:
        sys.exit('missing: ' + ', '.join(missing))
    aspects = {}
    for key, stem in PAIRS.items():
        imgs = {t: Image.open(SRC / f'{stem}-{t}.png').convert('RGBA') for t in ('day', 'night')}
        boxes = [im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox() for im in imgs.values()]
        top = min(b[1] for b in boxes)
        bottom = max(b[3] for b in boxes)
        w = imgs['day'].width
        for t, im in imgs.items():
            im = im.crop((0, max(0, top - 12), w, min(im.height, bottom + 12)))
            im = im.resize((1440, round(im.height * 1440 / w)), Image.LANCZOS)
            if t == 'night':
                im = halo(im, 170, 18 if key == 'garland' else 12, .9)
            path = OUT / f'painted-{key}-{t}.webp'
            im.save(path, 'WEBP', quality=88, method=6)
            print('WROTE', path, im.size, f'{path.stat().st_size // 1024} KB')
            aspects[key] = round(im.width / im.height, 4)
    ts = pathlib.Path('src/ui/winter/paintedAspects.ts')
    ts.write_text('/** Generated by scripts/art/winter/codex-post.py: width/height of the cropped painted layers. */\n'
                  f"export const PAINTED_ASPECTS = {{ garland: {aspects['garland']}, hills: {aspects['hills']} }} as const;\n")
    print('WROTE', ts, aspects)


main()
