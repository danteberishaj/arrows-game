#!/usr/bin/env python3
"""WINTER-01: in-game winter frame + snowfall assets.

  /usr/bin/python3 scripts/art/winter/board-post.py [snow|frame|all]
snow  : draws the two snowfall tiles (procedural, seamless vertically) -> assets/images/winter/snowfall-{near,far}-{day,night}.webp
frame : crops the Codex layers artifacts/WINTER-01/concepts/board/{drift,frost}-{day,night}.png to the union of their alpha
        bounds (day/night stay aligned), scales to 1080 wide -> assets/images/winter/board-{drift,frost}-{day,night}.webp
        and writes src/ui/winter/boardAspects.ts. Exits non-zero if an input is missing.
Day flakes are pale blue-grey (white would vanish on the #EEF4FB board); night flakes are white.
"""
import pathlib
import random
import sys

from PIL import Image, ImageDraw, ImageFilter

OUT = pathlib.Path('assets/images/winter')
SRC = pathlib.Path('artifacts/WINTER-01/concepts/board')
TILE = (720, 1600)  # width/height 0.45: at phone width the tile is taller than the board viewport
LAYERS = {  # name: (count, radius range px, blur px, alpha)
    'near': (18, (9.0, 14.0), 2.0, 240),  # owner 2026-11-18: bigger, 'barely see it'
    'far': (30, (4.5, 7.0), 0.8, 210),
}
COLOURS = {'day': (176, 196, 226), 'night': (255, 255, 255)}


def tile(name, mode, seed):
    count, (rmin, rmax), blur, alpha = LAYERS[name]
    rnd = random.Random(seed)
    w, h = TILE
    im = Image.new('RGBA', TILE, COLOURS[mode] + (0,))
    mask = Image.new('L', TILE, 0)
    d = ImageDraw.Draw(mask)
    for _ in range(count):
        x, y, r = rnd.uniform(0, w), rnd.uniform(0, h), rnd.uniform(rmin, rmax)
        a = int(alpha * rnd.uniform(0.6, 1.0))
        for dy in (-h, 0, h):  # wrap so the tile repeats seamlessly
            d.ellipse((x - r, y + dy - r, x + r, y + dy + r), fill=a)
    im.putalpha(mask.filter(ImageFilter.GaussianBlur(blur)))
    return im


def snow():
    for i, name in enumerate(LAYERS):
        for mode in COLOURS:
            path = OUT / f'snowfall-{name}-{mode}.webp'
            tile(name, mode, 7 + i).save(path, 'WEBP', quality=90, method=6)
            print('WROTE', path, f'{path.stat().st_size // 1024} KB')


def frame():
    missing = [f'{k}-{t}.png' for k in ('drift', 'frost') for t in ('day', 'night') if not (SRC / f'{k}-{t}.png').exists()]
    if missing:
        sys.exit('missing: ' + ', '.join(missing))
    aspects = {}
    for key in ('drift', 'frost'):
        imgs = {t: Image.open(SRC / f'{key}-{t}.png').convert('RGBA') for t in ('day', 'night')}
        boxes = [im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox() for im in imgs.values()]
        top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
        for t, im in imgs.items():
            w = im.width
            im = im.crop((0, top, w, bottom)).resize((1080, round((bottom - top) * 1080 / w)), Image.LANCZOS)
            path = OUT / f'board-{key}-{t}.webp'
            im.save(path, 'WEBP', quality=88, method=6)
            print('WROTE', path, im.size, f'{path.stat().st_size // 1024} KB')
            aspects[key] = round(im.width / im.height, 4)
    ts = pathlib.Path('src/ui/winter/boardAspects.ts')
    ts.write_text('/** Generated by scripts/art/winter/board-post.py: width/height of the cropped board frame layers. */\n'
                  f"export const BOARD_ASPECTS = {{ drift: {aspects['drift']}, frost: {aspects['frost']} }} as const;\n")
    print('WROTE', ts, aspects)


arg = sys.argv[1] if len(sys.argv) > 1 else 'all'
if arg in ('snow', 'all'):
    snow()
if arg in ('frame', 'all'):
    frame()
